-- The live schema lacked both tables that Invocacoes.jsx and Combate.jsx query.

CREATE TABLE IF NOT EXISTS public.summons (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    animal_type text NOT NULL,
    description text NOT NULL DEFAULT '',
    base_hp integer NOT NULL DEFAULT 100 CHECK (base_hp > 0),
    base_atk integer NOT NULL DEFAULT 10 CHECK (base_atk >= 0),
    element text,
    rarity text NOT NULL DEFAULT 'Comum',
    req_level integer NOT NULL DEFAULT 1 CHECK (req_level >= 1),
    req_rank text NOT NULL DEFAULT 'Estudante da Academia',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.player_summons (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id integer NOT NULL REFERENCES public.players(id) ON DELETE CASCADE,
    summon_id integer NOT NULL REFERENCES public.summons(id) ON DELETE CASCADE,
    level integer NOT NULL DEFAULT 1 CHECK (level >= 1),
    affection integer NOT NULL DEFAULT 0 CHECK (affection BETWEEN 0 AND 100),
    is_equipped boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT player_summons_unique_contract UNIQUE (player_id, summon_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS player_summons_one_equipped_per_player_idx
    ON public.player_summons(player_id) WHERE is_equipped IS TRUE;

ALTER TABLE public.summons ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.player_summons ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS summons_catalog_read ON public.summons;
CREATE POLICY summons_catalog_read ON public.summons
    FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS player_summons_select_own ON public.player_summons;
CREATE POLICY player_summons_select_own ON public.player_summons
    FOR SELECT TO authenticated
    USING (EXISTS (
        SELECT 1 FROM public.players p
        WHERE p.id = player_summons.player_id AND p.user_id = (SELECT auth.uid())
    ));

REVOKE ALL ON TABLE public.summons FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.summons TO anon, authenticated;

REVOKE ALL ON TABLE public.player_summons FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.player_summons TO authenticated;

