-- Minimal synthetic schema for the offline Dojo journey. Not a deployment baseline.
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE anon NOLOGIN;
CREATE ROLE service_role NOLOGIN;
CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE
AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
GRANT USAGE ON SCHEMA auth TO authenticated;

CREATE TABLE public.players (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL,
    name text NOT NULL UNIQUE,
    village_id integer NOT NULL,
    character_id text NOT NULL,
    avatar text NOT NULL,
    class text NOT NULL,
    rank text DEFAULT 'Estudante da Academia',
    clan text,
    clan_lvl integer DEFAULT 0,
    clan_custom_stats jsonb DEFAULT '{}'::jsonb,
    element text,
    level integer DEFAULT 1,
    xp bigint DEFAULT 0,
    ryous integer DEFAULT 0,
    hp integer DEFAULT 130,
    chakra integer DEFAULT 120,
    stamina integer DEFAULT 120,
    is_fainted boolean DEFAULT false,
    fainted_at timestamptz,
    pontos_atributos integer DEFAULT 0,
    forca integer, agilidade integer, resistencia integer, inteligencia integer,
    energia integer, ninjutsu integer, taijutsu integer, genjutsu integer,
    bukijutsu integer, selo integer, nin integer, tai integer, gen integer, buk integer,
    wins_dojo integer DEFAULT 0, dojo_clears integer DEFAULT 0, losses_dojo integer DEFAULT 0,
    daily_map_battles integer DEFAULT 0, daily_chakra_spent integer DEFAULT 0,
    daily_trainings integer DEFAULT 0, daily_npcs_defeated integer DEFAULT 0,
    npc_wins integer DEFAULT 0, vip_coins integer DEFAULT 0,
    passou_exame_chunin boolean DEFAULT false,
    jutsus_learned jsonb DEFAULT '[]'::jsonb,
    inventory_essences jsonb DEFAULT '{}'::jsonb
);
CREATE TABLE public.villages(id integer PRIMARY KEY);
CREATE TABLE public.characters(id text PRIMARY KEY);
CREATE TABLE public.avatars(id text PRIMARY KEY, character_id text REFERENCES public.characters, is_base boolean);
CREATE TABLE public.ranks(id integer PRIMARY KEY, title text, name_id text, train_min_mult numeric, train_max_mult numeric, train_bonus integer);
CREATE TABLE public.attributes(field text PRIMARY KEY, hero_min integer, hero_max integer);
CREATE TABLE public.npcs(
    id integer PRIMARY KEY, name text NOT NULL, level integer, hp integer, atk integer, def integer,
    chakra integer, element text, xp_reward integer, ryou_reward integer,
    is_active boolean DEFAULT true, is_map_npc boolean DEFAULT false, is_story_mode boolean DEFAULT false,
    is_bingo_book boolean DEFAULT false, is_chunin_exam boolean DEFAULT false
);
CREATE TABLE public.jutsus(id integer PRIMARY KEY, is_active boolean, cooldown integer, chakra_cost integer, category text, accuracy integer, damage integer, element text);
CREATE TABLE public.player_jutsus(player_id integer, jutsu_id integer);
CREATE TABLE public.player_defeated_npcs(player_id integer, npc_id integer, PRIMARY KEY (player_id,npc_id));
CREATE TABLE public.items(id integer PRIMARY KEY, name text, bonus_stats jsonb);
CREATE TABLE public.item_stat_types(name text, is_percentage boolean, stat_type text);
CREATE TABLE public.player_inventory(
    player_id integer, item_id integer, is_equipped boolean, is_favorite boolean,
    rarity text, rolled_stats jsonb, upgrade_level integer
);
CREATE TABLE public.battle_logs(
    player_id integer, enemy_name text, result text, xp_gained integer,
    ryous_gained integer, turn_count integer, combat_log jsonb
);

