const availableFiles = new Set(VERIFIED_LOCAL_PROFILE_FILES);
const canonicalSourcePattern = /^https:\/\/narutogame\.com\.br\/assets\/images\/+logado\/profile(?:-4x4)?\/(\d+)\/(\d+)\.png$/i;

export function resolveLocalCharacterPortrait(src) {
  if (typeof src !== "string") return src;
  const trimmed = src.trim();
  if (trimmed.startsWith("/images/") && !trimmed.startsWith("//") && !trimmed.includes("..")) {
    return trimmed;
  }
  const mappedFile = LOCAL_CHARACTER_PORTRAIT_MAP[trimmed];
  if (mappedFile && availableFiles.has(mappedFile)) {
    return "/images/characters/" + mappedFile;
  }
  const match = canonicalSourcePattern.exec(trimmed);
  if (!match) return src;
  const file = match[1] + "-" + match[2] + ".png";
  return availableFiles.has(file) ? "/images/characters/" + file : src;
}

export function hasLocalCharacterPortrait(src) {
  if (typeof src !== "string") return false;
  const resolved = resolveLocalCharacterPortrait(src);
  return typeof resolved === "string" && resolved.startsWith("/images/") && !resolved.startsWith("//") && !resolved.includes("..");
}
