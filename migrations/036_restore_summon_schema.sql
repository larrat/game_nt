CREATE OR REPLACE FUNCTION public.assinar_invocacao(
    p_player_id integer,
    p_invocacao_id integer
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $function$
DECLARE
    v_player public.players%ROWTYPE;
    v_invocacao public.summons%ROWTYPE;
    v_cost integer;
    v_player_rank integer;
    v_required_rank integer;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Autenticação obrigatória.';
    END IF;

    SELECT * INTO v_player
    FROM public.players
    WHERE id = p_player_id AND user_id = auth.uid()
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Personagem não encontrado ou ação não autorizada.';
    END IF;

    SELECT * INTO v_invocacao
    FROM public.summons
    WHERE id = p_invocacao_id;

    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'error', 'Invocação não encontrada.');
    END IF;

    IF EXISTS (
        SELECT 1 FROM public.player_summons ps
        WHERE ps.player_id = p_player_id AND ps.summon_id = p_invocacao_id
    ) THEN
        RETURN jsonb_build_object('success', false, 'error', 'Você já possui essa invocação.');
    END IF;

    v_player_rank := CASE lower(COALESCE(v_player.rank, ''))
        WHEN 'estudante da academia' THEN 0
        WHEN 'genin' THEN 1 WHEN 'chunin' THEN 2
        WHEN 'jounin' THEN 3 WHEN 'jonin' THEN 3
        WHEN 'anbu' THEN 4 WHEN 'sannin' THEN 5
        WHEN 'herói' THEN 6 WHEN 'heroi' THEN 6
        ELSE 0 END;
    v_required_rank := CASE lower(COALESCE(v_invocacao.req_rank, 'estudante da academia'))
        WHEN 'estudante da academia' THEN 0
        WHEN 'genin' THEN 1 WHEN 'chunin' THEN 2
        WHEN 'jounin' THEN 3 WHEN 'jonin' THEN 3
        WHEN 'anbu' THEN 4 WHEN 'sannin' THEN 5
        WHEN 'herói' THEN 6 WHEN 'heroi' THEN 6
        ELSE 99 END;

    IF COALESCE(v_player.level, 1) < v_invocacao.req_level
       OR v_player_rank < v_required_rank THEN
        RETURN jsonb_build_object('success', false, 'error', 'Requisitos de nível ou graduação não atendidos.');
    END IF;

    v_cost := GREATEST(0, COALESCE(v_invocacao.req_level, 1) * 100);
    IF COALESCE(v_player.ryous, 0) < v_cost THEN
        RETURN jsonb_build_object('success', false, 'error', 'Ryous insuficientes.', 'cost', v_cost);
    END IF;

    UPDATE public.players
    SET ryous = COALESCE(ryous, 0) - v_cost
    WHERE id = p_player_id;

    INSERT INTO public.player_summons (player_id, summon_id, is_equipped)
    VALUES (p_player_id, p_invocacao_id, false);

    RETURN jsonb_build_object('success', true, 'cost', v_cost);
END;
$function$;

REVOKE ALL ON FUNCTION public.assinar_invocacao(integer, integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.assinar_invocacao(integer, integer) TO authenticated, service_role;


CREATE OR REPLACE FUNCTION public.equipar_invocacao(
    p_player_id integer,
    p_player_summon_id integer,
    p_equipped boolean
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $function$
DECLARE
    v_player public.players%ROWTYPE;
    v_owned_summon public.player_summons%ROWTYPE;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Autenticação obrigatória.';
    END IF;

    SELECT * INTO v_player
    FROM public.players
    WHERE id = p_player_id AND user_id = auth.uid()
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Personagem não encontrado ou ação não autorizada.';
    END IF;

    IF COALESCE(p_equipped, false) IS TRUE THEN
        IF p_player_summon_id IS NULL THEN
            RETURN jsonb_build_object('success', false, 'error', 'Invocação não informada.');
        END IF;

        SELECT * INTO v_owned_summon
        FROM public.player_summons
        WHERE id = p_player_summon_id AND player_id = p_player_id
        FOR UPDATE;

        IF NOT FOUND THEN
            RETURN jsonb_build_object('success', false, 'error', 'Contrato de invocação não encontrado.');
        END IF;

        UPDATE public.player_summons
        SET is_equipped = false
        WHERE player_id = p_player_id AND is_equipped IS TRUE;

        UPDATE public.player_summons
        SET is_equipped = true
        WHERE id = p_player_summon_id AND player_id = p_player_id;
    ELSE
        IF p_player_summon_id IS NULL THEN
            UPDATE public.player_summons
            SET is_equipped = false
            WHERE player_id = p_player_id;
        ELSE
            UPDATE public.player_summons
            SET is_equipped = false
            WHERE id = p_player_summon_id AND player_id = p_player_id;
        END IF;
    END IF;

    RETURN jsonb_build_object('success', true);
END;
$function$;

REVOKE ALL ON FUNCTION public.equipar_invocacao(integer, integer, boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.equipar_invocacao(integer, integer, boolean) TO authenticated, service_role;

